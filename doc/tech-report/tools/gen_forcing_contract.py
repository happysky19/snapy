def check(report=REPORT):
    try:
        expected = generate(Path(report))
        actual = (Path(report) / TARGET).read_text()
        errors = [] if actual == expected else ['generated signature, shapes, registration or runtime example differs from the pin']
    except (OSError, ValueError, subprocess.CalledProcessError) as exc:
        errors = [str(exc)]
    print(f'[N6 forcing contract] {len(errors)} problem(s)')
    for error in errors:
        print('  ' + error)
    return int(bool(errors))


