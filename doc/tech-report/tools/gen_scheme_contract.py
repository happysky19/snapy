"""N6: extract the scheme (reconstruction / Riemann solver) interface from the code pin; verify the block."""
import re
import subprocess
import sys
from pathlib import Path

import code_anchors

REPORT = Path(__file__).resolve().parent.parent
TARGET = 'book/chapters/04-spatial-discretization/_howto.qmd'
PIN = '919936da07d80a310b98ab11da184972a3203274'


def generate(report):
    repo, sha = code_anchors.read_pin(report / 'code_pin.yml')
    if sha != PIN:
        raise ValueError('N6 scheme contract needs review when the code pin changes')
    checkout = code_anchors.find_commit(repo, sha)

    def read(path):
        return subprocess.run(['git', '-C', str(checkout), 'show', f'{sha}:{path}'],
                              check=True, capture_output=True, text=True).stdout

    def excerpt(path, pattern):
        text = read(path)
        matches = list(re.finditer(pattern, text, re.M | re.S))
        if len(matches) != 1:
            raise ValueError(f'{path}: expected one match, got {len(matches)}')
        match = matches[0]
        line = text[:match.start()].count('\n') + 1
        return (match[0].strip(),
                f'[`{path}:{line}`](https://github.com/{repo}/blob/{sha}/{path}#L{line})')

    def deck_shock():
        """Split examples/*.yaml at the pin by their reconstruct `shock:` values, with one cited line per group."""
        names = subprocess.run(['git', '-C', str(checkout), 'ls-tree', '--name-only', sha, 'examples/'],
                               check=True, capture_output=True, text=True).stdout.split()
        groups = {}
        for path in sorted(n for n in names if n.endswith('.yaml')):
            text = read(path)
            hits = [(text[:m.start()].count('\n') + 1, m.group(2)) for m in re.finditer(
                r'^\s*(vertical|horizontal):[^\n]*\bshock:\s*(true|false)\b', text, re.M)]
            values = {v for _, v in hits}
            key = values.pop() if len(values) == 1 else ('mixed' if values else 'unset')
            line = hits[0][0] if hits else 1
            groups.setdefault(key, []).append(
                f'[`{path}:{line}`](https://github.com/{repo}/blob/{sha}/{path}#L{line})')
        return len([n for n in names if n.endswith('.yaml')]), groups

    def shock_split(total, groups):
        label = {'false': 'set `shock: false`', 'true': 'set `shock: true`',
                 'mixed': 'mix the two', 'unset': 'leave it unset'}
        parts = [f'{len(groups[k])} {label[k]} (e.g. {groups[k][0]})'
                 for k in ('false', 'true', 'mixed', 'unset') if k in groups]
        return f'of the {total} decks in `examples/`, ' + ', '.join(parts[:-1]) + \
            (' and ' if len(parts) > 1 else '') + parts[-1]

    interface, interface_cite = excerpt('src/recon/reconstruct.hpp',
        r'  torch::Tensor forward\(torch::Tensor w, int dim, bool floor = true\);')
    option, option_cite = excerpt('python/csrc/pyrecon.cpp',
        r'      \.ADD_OPTION\(std::string, snap::InterpOptionsImpl, type\)')
    deck_line, deck_cite = excerpt('examples/straka_single.yaml', r'    vertical: \{type: [^\n]+\}')
    faces, faces_cite = excerpt('src/recon/reconstruct.cpp',
        r'  auto outl = wlr\[IRT\]\.slice\(dim, il - 1, iu \+ 1\);\n  auto outr = wlr\[ILT\]\.slice\(dim, il, iu \+ 2\);')
    _, ends_cite = excerpt('src/recon/reconstruct.cpp',
        r'  wlr\[ILT\]\.slice\(dim, 0, il\) = wlr\[ILT\]\.select\(dim, il\)\.unsqueeze\(dim\);')
    width, width_cite = excerpt('src/recon/reconstruct.cpp', r'  int nghost = pinterp1->stencils\(\) / 2 \+ 1;')
    clamp, clamp_cite = excerpt('src/recon/reconstruct.cpp',
        r'  if \(phydro == nullptr\) \{\n[^\n]+\n    result\.clamp_min_\(0\.\);')
    stencils, stencils_cite = excerpt('src/recon/interpolation.hpp', r'  virtual int stencils\(\) const \{ return 1; \}')
    dims, dims_cite = excerpt('src/hydro/hydro_forward.cpp', r'  enum \{ DIM1 = 3, DIM2 = 2, DIM3 = 1 \};')
    shock, shock_cite = excerpt('src/recon/reconstruct.hpp', r'  ADD_ARG\(bool, shock\) = true;')
    shock_decks = shock_split(*deck_shock())
    return f'''<!-- generated reader-reference: scheme-contract -->
<!-- Generated by tools/gen_scheme_contract.py; do not edit. -->
#### How to add one

**A minimal input.** Follow steps 0–5 in one Python file, run from the repository root. The example
prototypes a reconstruction in Python and checks it, value for value, against the built-in one it copies.

0. Prepare a smooth, positive five-variable column along $x_1$, shaped (variables, $x_3$, $x_2$, $x_1$).

```python
import torch
import snapy

def column(n=8):
    """(5, 1, 1, n) float64: density, three velocities, pressure, all in [1, 2]."""
    x = torch.linspace(1., 2., n, dtype=torch.float64)
    return x.reshape(1, 1, 1, n).repeat(5, 1, 1, 1)

w = column()
```

1. Write the method with the generated interface ({interface_cite}): it takes the cell state and the tensor
   dimension, and returns the left and right face states stacked as (2, *w.shape).

```python
def donor_cell(w: torch.Tensor, dim: int) -> torch.Tensor:
    out = torch.empty((2,) + tuple(w.shape),
                      dtype=w.dtype, device=w.device)
    left, right = out[0], out[1]
    n = w.size(dim)
    # face i: cell i-1 on its left, cell i on its right
    left.narrow(dim, 1, n - 1).copy_(w.narrow(dim, 0, n - 1))
    right.copy_(w)
    # the outer face repeats the first inner one
    left.narrow(dim, 0, 1).copy_(left.narrow(dim, 1, 1))
    right.narrow(dim, 0, 1).copy_(right.narrow(dim, 1, 1))
    return out
```

2. Select it by its type name with the generated option ({option_cite}). The deck lives at
   `examples/straka_single.yaml`, whose line ({deck_cite}) is `{deck_line}`.

```python
interp = snapy.InterpOptions()
interp.type("dc")
```

3. Build the built-in module that the name selects.

```python
options = snapy.ReconstructOptions()
options.interp(interp)
options.shock(False)
reference = snapy.Reconstruct(options)
```

4. Run both along $x_1$, which is tensor dimension 3.

```python
mine, theirs = donor_cell(w, 3), reference.forward(w, 3, True)
```

5. Check the effect: the two agree exactly, in the stacked (2, variables, $x_3$, $x_2$, $x_1$) layout.

```python
assert theirs.shape == (2, 5, 1, 1, 8)
torch.testing.assert_close(mine, theirs, rtol=0, atol=0)
print("N6 scheme: donor cell matches the built-in dc reconstruction exactly")
```

- **Contract.** Interface: `{interface}` returns the two face states stacked in slots `ILT` = 0 and
  `IRT` = 1, filled by these lines ({faces_cite}): `{faces.splitlines()[0].strip()}` and
  `{faces.splitlines()[1].strip()}`. Step 5 checks the result exactly: at face $i$, slot 0 holds the
  value from cell $i-1$ and slot 1 the value from cell $i$.
- Faces ({ends_cite}): outside the computed range, the end faces are copied inward.
- Stencil and ghost width: a method declares its stencil, one cell by default ({stencils_cite}): `{stencils}`;
  the reconstruction's ghost width is `{width}` ({width_cite}).
- Dimension: the tensor dimension is 3 for $x_1$, 2 for $x_2$ and 1 for $x_3$ ({dims_cite}): `{dims}`.
- Standalone use: without a parent hydro the result is clamped to non-negative values ({clamp_cite}), so
  prototype on a positive state, as step 0 does.
- Shock flag: `{shock}` ({shock_cite}); {shock_decks}. Step 3 sets it false, as the Straka deck does.
- C++ route: a reconstruction or Riemann solver built into the library follows the native C++ route
  below, which is the one recipe for both kinds of scheme: selection, lookup, the classes, the face slots,
  the shapes and the rebuild.

CI checks the contract, and the runtime test runs on a pin build.
<!-- end reader-reference: scheme-contract -->
'''


def check(report=REPORT):
    try:
        expected = generate(Path(report))
        actual = (Path(report) / TARGET).read_text()
        errors = [] if actual == expected else ['generated interface, faces, dispatch or runtime example differs from the pin']
    except (OSError, ValueError, subprocess.CalledProcessError) as exc:
        errors = [str(exc)]
    print(f'[N6 scheme contract] {len(errors)} problem(s)')
    for error in errors:
        print('  ' + error)
    return int(bool(errors))


if __name__ == '__main__':
    if '--write' in sys.argv:
        (REPORT / TARGET).write_text(generate(REPORT))
    else:
        sys.exit(check())
